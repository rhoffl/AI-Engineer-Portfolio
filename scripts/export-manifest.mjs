// Writes portfolio/manifest.yaml and portfolio/evidence-ledger.yaml from the site content.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import YAML from "yaml";

const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const projects = readdirSync("src/content/projects").map((f) => read(`src/content/projects/${f}`)).sort((a, b) => a.order - b.order);
const supporting = read("src/content/supporting.json");
const ledger = read("src/content/ledger.json");
mkdirSync("portfolio", { recursive: true });

const manifest = {
  projects: [
    ...projects.map((p) => ({
      id: p.slug,
      title: p.title,
      tier: "flagship",
      status: p.status,
      source_archive: p.sourceArchive,
      diagram: p.diagramFile,
      verified_metrics: p.evaluation.metrics.filter((m) => m.status === "measured").map((m) => ({ name: m.name, result: m.result, dataset: m.dataset, test_date: m.testDate })),
      target_metrics: p.evaluation.metrics.filter((m) => m.status !== "measured").map((m) => m.name.toLowerCase().replace(/@/g, "_at_").replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "")),
    })),
    ...supporting.map((s) => ({ id: s.slug, title: s.title, tier: "supporting", status: s.status })),
  ],
};
const header = "# Generated by `npm run manifest` from src/content. Edit the JSON, not this file.\n";
writeFileSync("portfolio/manifest.yaml", header + YAML.stringify(manifest));
writeFileSync("portfolio/evidence-ledger.yaml", header + YAML.stringify({ labels: { implemented: "Working capability exists", measured: "Repeatable test results exist", planned: "Design or roadmap item" }, claims: ledger }));
console.log("Wrote portfolio/manifest.yaml and portfolio/evidence-ledger.yaml");
